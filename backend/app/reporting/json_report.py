from typing import Dict, List
from datetime import datetime


def generate_json_report(scan: dict, findings: List[Dict], verification: Dict = None) -> Dict:
    by_sev, by_cat, by_pri = {}, {}, {}
    for f in findings:
        by_sev[f.get("severity", "?")] = by_sev.get(f.get("severity", "?"), 0) + 1
        by_cat[f.get("category", "?")] = by_cat.get(f.get("category", "?"), 0) + 1
        by_pri[f.get("priority", "P4")] = by_pri.get(f.get("priority", "P4"), 0) + 1

    def overall_risk(s):
        for level in ("CRITICAL", "HIGH", "MEDIUM", "LOW"):
            if s.get(level, 0) > 0:
                return level
        return "CLEAN"

    return {
        "report_metadata": {
            "generated_at": datetime.utcnow().isoformat(),
            "tool": "RepoGuard AI",
            "version": "1.0.0",
            "scan_id": scan.get("id"),
        },
        "project": {
            "name": scan.get("project_name"),
            "description": scan.get("project_description"),
            "scan_date": scan.get("created_at"),
        },
        "executive_summary": {
            "total_findings": len(findings),
            "by_severity": by_sev,
            "by_category": by_cat,
            "by_priority": by_pri,
            "risk_level": overall_risk(by_sev),
        },
        "findings": findings,
        "verification": verification,
        "scanners_used": ["gitleaks", "trivy", "osv-scanner"],
        "disclaimer": "This report was generated by automated security scanners. Human review is recommended.",
    }

